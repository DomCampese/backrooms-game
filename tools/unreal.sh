#!/bin/bash
# Build, open, play and test the Unreal project (unreal/) from the terminal.
#
#   tools/unreal.sh build     compile the editor modules (after every pull)
#   tools/unreal.sh open      build, then open the project in the editor
#   tools/unreal.sh play      build, bring the sounds and materials up to date, then run the game
#   tools/unreal.sh test      build, then run the Backrooms automation tests
#   tools/unreal.sh surfaces  write the Web build's textures and world.json for the editor (texdump)
#   tools/unreal.sh import    build, then import assets/sounds and build the world's materials,
#                             headless (no editor window); `make unreal-materials`
#   tools/unreal.sh log       the "Backrooms:" lines from the last run's log
#
# `make unreal`, `make unreal-open`, `make unreal-play` and `make unreal-test`
# call the same. UE_ROOT is the engine (default: the Launcher's 5.8 install).
# play takes LEVEL and SEED, as the Web build's BACKROOMS_LEVEL and
# BACKROOMS_SEED: `LEVEL=1 SEED=42 tools/unreal.sh play`.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
PROJECT="$ROOT/unreal/BackroomsGame.uproject"
UE_ROOT=${UE_ROOT:-"/Users/Shared/Epic Games/UE_5.8"}
EDITOR="$UE_ROOT/Engine/Binaries/Mac/UnrealEditor.app/Contents/MacOS/UnrealEditor"
EDITOR_CMD="$UE_ROOT/Engine/Binaries/Mac/UnrealEditor-Cmd"
LOG="$ROOT/unreal/Saved/Logs/BackroomsGame.log"
# backrooms_world.py reads the textures from here.
SURFACES="$ROOT/unreal/Saved/Surfaces"

die() { echo "unreal.sh: $*" >&2; exit 1; }

[[ -d "$UE_ROOT/Engine" ]] || die "no engine at $UE_ROOT; set UE_ROOT to the UE_5.8 folder"

build() {
    # The editor holds the plugin's binaries open, and a build under it either
    # fails to write them or is replaced by the running copy.
    if pgrep -x UnrealEditor >/dev/null; then
        die "quit the Unreal editor first; it locks the plugin while it is open"
    fi
    # Files the repository does not have, under folders Unreal compiles: a class
    # made from the editor's New C++ Class menu stopped a build here once
    # (TestHyd.h, "Expected a GENERATED_BODY()"), and read as the port's fault.
    local stray
    stray=$(cd "$ROOT" && git ls-files --others --exclude-standard -- unreal/Source unreal/Plugins/*/Source)
    if [[ -n "$stray" ]]; then
        echo "unreal.sh: these are not in the repository, and Unreal will compile them:" >&2
        echo "$stray" | sed 's/^/    /' >&2
        echo "unreal.sh: delete them if you did not mean to add them" >&2
    fi
    "$UE_ROOT/Engine/Build/BatchFiles/Mac/Build.sh" BackroomsGameEditor Mac Development \
        -Project="$PROJECT" -WaitMutex
}

# The surfaces are generated by the Web build's code, so they are written
# fresh rather than committed: a change to web/src/surfaces.cpp reaches the editor
# the next time it opens the project.
surfaces() {
    make -C "$ROOT" texdump
    mkdir -p "$SURFACES"
    "$ROOT/texdump" --unreal "$SURFACES" "$ROOT/assets/models/revolver.glb" >/dev/null
    echo "unreal.sh: wrote the textures and world.json to $SURFACES"
}

# The editor's Python, headless: the sounds and the world's textures and
# materials, as opening the editor builds them, with no window.
materials() {
    surfaces
    "$EDITOR_CMD" "$PROJECT" -run=pythonscript \
        -script="import backrooms_import, backrooms_world; backrooms_import.import_sounds(); backrooms_world.build()" \
        -unattended -nosplash -log || true
    grep "Backrooms:" "$LOG" || echo "(no Backrooms lines in $LOG)"
}

# What the materials are built from: the surfaces texdump writes, the editor's
# Python, and the list of recordings. The digest of the last good build is
# kept beside the surfaces, so a play rebuilds only when one of these moved.
STAMP="$ROOT/unreal/Saved/materials.digest"
inputs_digest() {
    local sum=sha256sum
    command -v sha256sum >/dev/null || sum="shasum -a 256"
    (cd "$ROOT" && {
        find unreal/Saved/Surfaces -type f | LC_ALL=C sort | while read -r f; do echo "$f"; cat "$f"; done
        cat unreal/Plugins/Backrooms/Content/Python/*.py
        find assets/sounds -name '*.ogg' | LC_ALL=C sort
    }) | $sum | cut -d' ' -f1
}

# The game cannot import or build materials, so a play does it first, with the
# editor's Python and no window, when the project lacks one or its inputs changed.
materials_if_stale() {
    surfaces
    local want reason=""
    want=$(inputs_digest)
    for asset in World/MPC_Backrooms World/M_BackroomsWorld World/M_BackroomsWorldBlend World/M_BackroomsShape \
                 World/M_BackroomsShapeBlend World/M_BackroomsBillboard World/M_BackroomsBillboardAdd \
                 World/M_BackroomsPost World/M_BackroomsTape World/M_BackroomsClear Sounds/water/swim_1; do
        if [ ! -f "$ROOT/unreal/Content/Backrooms/$asset.uasset" ]; then
            reason="$asset is not built yet"
            break
        fi
    done
    if [ -z "$reason" ] && [ "$(cat "$STAMP" 2>/dev/null)" != "$want" ]; then
        reason="the textures or the material code changed"
    fi
    if [ -z "$reason" ]; then
        echo "unreal.sh: the sounds and materials are up to date"
        return
    fi
    echo "unreal.sh: $reason; building the sounds and materials (no editor window, a minute or two)"
    materials
    if grep -q "built the world's materials" "$LOG"; then
        echo "$want" >"$STAMP"
    else
        echo "unreal.sh: the materials did not build; the lines above say why" >&2
    fi
}

case "${1:-build}" in
build)
    build
    ;;
open)
    build
    surfaces
    open -a "$UE_ROOT/Engine/Binaries/Mac/UnrealEditor.app" --args "$PROJECT"
    ;;
play)
    build
    materials_if_stale
    # With neither, the game opens on its title screen, as the Web build does.
    MAP="/Engine/Maps/Entry${LEVEL:+?level=$LEVEL}${SEED:+?seed=$SEED}"
    "$EDITOR" "$PROJECT" "$MAP" -game -windowed -ResX=1440 -ResY=850 -log || true
    echo "--- Backrooms lines from $LOG:"
    grep "Backrooms:" "$LOG" || echo "(none)"
    ;;
test)
    build
    "$EDITOR_CMD" "$PROJECT" -ExecCmds="Automation RunTests Backrooms; Quit" \
        -unattended -nullrhi -nosound -log || true
    echo "--- results:"
    grep -E "Test Completed|Result=\{" "$LOG" || echo "(no results in $LOG)"
    ;;
surfaces)
    surfaces
    ;;
import)
    build
    materials
    grep -q "built the world's materials" "$LOG" && inputs_digest >"$STAMP"
    ;;
log)
    grep "Backrooms:" "$LOG" || echo "(no Backrooms lines in $LOG)"
    ;;
*)
    sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//'
    exit 1
    ;;
esac
